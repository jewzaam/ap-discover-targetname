# Raw layout: RAW/<rig>/DATE_<date>/<frame>
PRIMARY_RIG = "SQA55@f5.3+AP26CC"
SECONDARY_RIG = "Raptor@f4.5+XSi"
FRAME_NAME = "2026-10-14_08-12-10_HFR_2.77_RMSAC_0.00_TEMP_26.00.fits"


def raw_path(root, rig, name, *, date="2026-10-14"):
    return root / "RAW" / rig / f"DATE_{date}" / name


def make_datum(filename, *, ra="328.4", dec="47.27", targetname=None):
    return {
        "filename": str(filename),
        "type": "LIGHT",
        "ra": ra,
        "dec": dec,
        "targetname": targetname,
    }


def make_reference_datum(name, **kwargs):
    """Reference metadata only; no file needed since it is never renamed."""
    return make_datum(raw_path(Path("F:/"), PRIMARY_RIG, name), **kwargs)


def make_frame(tmp_path, name=FRAME_NAME, *, date="2026-10-14"):
    """Placeholder secondary frame at RAW/<secondary rig>/DATE_<date>/<name>."""
    frame = raw_path(tmp_path, SECONDARY_RIG, name, date=date)
    frame.parent.mkdir(parents=True, exist_ok=True)
    frame.write_bytes(b"fits")
    return frame


