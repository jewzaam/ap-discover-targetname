class TestDiscoverTargetnames:
    @patch("ap_common.get_filtered_metadata")
    def test_renames_and_counts(self, mock_get_metadata, tmp_path):
        source_dir = tmp_path / "RAW" / SECONDARY_RIG
        reference_dir = tmp_path / "RAW" / PRIMARY_RIG
        night_1 = make_frame(tmp_path, name="2026-10-14_08-12-10.fits")
        night_1_slew = make_frame(tmp_path, name="2026-10-14_08-13-19.fits")
        night_2 = make_frame(
            tmp_path, name="2026-10-15_08-12-10.fits", date="2026-10-15"
        )
        reference = raw_path(tmp_path, PRIMARY_RIG, "2026-10-14_08-11-07.fits")
        reference.parent.mkdir(parents=True)
        mock_get_metadata.side_effect = [
            {str(reference): make_datum(reference, targetname="Cocoon Nebula")},
            {
                str(night_1): make_datum(night_1),
                str(night_1_slew): make_datum(night_1_slew, ra="0", dec="0"),
                str(night_2): make_datum(night_2),
            },
        ]

        counts = discover_targetnames(
            str(source_dir), str(reference_dir), max_separation_degrees=1.0, quiet=True
        )

        assert counts == {RESULT_RENAMED: 2, RESULT_UNMATCHED: 1, RESULT_SKIPPED: 0}
        # renamed in place: each frame stays in its own DATE directory
        assert sorted(p.name for p in night_1.parent.iterdir()) == [
            "2026-10-14_08-12-10_OBJECT_Cocoon Nebula.fits",
            "2026-10-14_08-13-19.fits",
        ]
        assert [p.name for p in night_2.parent.iterdir()] == [
            "2026-10-15_08-12-10_OBJECT_Cocoon Nebula.fits",
        ]
        reference_call, source_call = mock_get_metadata.call_args_list
        assert reference_call.kwargs["dirs"] == [str(reference_dir)]
        assert "targetname" in reference_call.kwargs["required_properties"]
        assert source_call.kwargs["dirs"] == [str(source_dir)]
        assert source_call.kwargs["filters"] == {"type": "LIGHT"}
        assert source_call.kwargs["recursive"] is True

    @patch("ap_common.get_filtered_metadata")
    def test_no_reference_raises(self, mock_get_metadata, tmp_path):
        mock_get_metadata.return_value = {
            "p": make_reference_datum("p.fits", targetname=None),
        }

        with pytest.raises(ValueError, match="No reference"):
            discover_targetnames(
                str(tmp_path), str(tmp_path), max_separation_degrees=1.0, quiet=True
            )

    @pytest.mark.parametrize("missing", ["source", "reference"])
    @patch("ap_common.get_filtered_metadata")
    def test_missing_directory_raises(self, mock_get_metadata, missing, tmp_path):
        dirs = {"source": str(tmp_path), "reference": str(tmp_path)}
        dirs[missing] = str(tmp_path / "30_Data")

        with pytest.raises(ValueError, match="Directory not found"):
            discover_targetnames(
                dirs["source"],
                dirs["reference"],
                max_separation_degrees=1.0,
                quiet=True,
            )
        mock_get_metadata.assert_not_called()


class TestRealHeaders:
    """
    Unmocked ap-common header loading on real FITS files: pins the contract that
    RA/DEC/OBJECT headers arrive as config.NORMALIZED_HEADER_RA/DEC and
    targetname. A wrong key would otherwise show up only as every frame skipped.
    """

    def test_renames_from_real_fits_headers(self, tmp_path):
        light = {"IMAGETYP": "LIGHT", "RA": 328.4, "DEC": 47.27}
        write_fits(
            raw_path(tmp_path, PRIMARY_RIG, "2026-10-14_08-11-07.fits"),
            {**light, "OBJECT": "Cocoon Nebula"},
        )
        untargeted = write_fits(
            raw_path(tmp_path, SECONDARY_RIG, "2026-10-14_08-12-10.fits"), light
        )
        targeted = write_fits(
            raw_path(tmp_path, SECONDARY_RIG, "2026-10-14_08-13-19.fits"),
            {**light, "OBJECT": "North America Nebula"},
        )

        counts = discover_targetnames(
            str(tmp_path / "RAW" / SECONDARY_RIG),
            str(tmp_path / "RAW" / PRIMARY_RIG),
            max_separation_degrees=1.0,
            quiet=True,
        )

        assert counts == {RESULT_RENAMED: 1, RESULT_UNMATCHED: 0, RESULT_SKIPPED: 1}
        assert sorted(p.name for p in untargeted.parent.iterdir()) == [
            "2026-10-14_08-12-10_OBJECT_Cocoon Nebula.fits",
            targeted.name,
        ]


