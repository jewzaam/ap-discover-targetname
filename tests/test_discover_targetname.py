class TestBuildReference:
    def test_ignores_frames_without_target_or_coordinates(self):
        data = {
            "a": make_reference_datum("a.fits", targetname="Cocoon Nebula"),
            "b": make_reference_datum("b.fits", targetname=None),
            "c": make_reference_datum("c.fits", targetname="Cocoon Nebula", ra=None),
            "d": make_reference_datum("d.fits", targetname="Cocoon Nebula", dec="bad"),
            # enrichment drops keys whose header is absent
            "e": {"filename": str(raw_path(Path("F:/"), PRIMARY_RIG, "e.fits"))},
        }
        reference = build_reference(data)

        assert list(reference) == ["Cocoon Nebula"]
        assert reference["Cocoon Nebula"] == pytest.approx((328.4, 47.27))

    def test_one_entry_per_target(self):
        data = {
            "a": make_reference_datum("a.fits", targetname="Cocoon Nebula"),
            "b": make_reference_datum("b.fits", targetname="Cocoon Nebula"),
            "c": make_reference_datum(
                "c.fits", targetname="North America Nebula", ra="314.7", dec="44.53"
            ),
        }

        reference = build_reference(data)

        assert sorted(reference) == ["Cocoon Nebula", "North America Nebula"]
        assert reference["North America Nebula"] == pytest.approx((314.7, 44.53))

    def test_panels_are_separate_targets(self):
        panel_1 = make_reference_datum(
            "a.fits", targetname="M31", ra="10.0", dec="41.0"
        )
        panel_1["panel"] = "1"
        panel_2 = make_reference_datum(
            "b.fits", targetname="M31", ra="11.5", dec="41.0"
        )
        panel_2["panel"] = "2"
        no_panel = make_reference_datum(
            "c.fits", targetname="M33", ra="23.5", dec="30.7"
        )
        no_panel["panel"] = ""

        reference = build_reference({"a": panel_1, "b": panel_2, "c": no_panel})

        assert sorted(reference) == ["M31 Panel 1", "M31 Panel 2", "M33"]
        assert reference["M31 Panel 2"] == pytest.approx((11.5, 41.0))


