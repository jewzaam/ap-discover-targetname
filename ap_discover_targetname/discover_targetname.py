"""
Generated By: Claude Code (claude-opus-5-5[1m])

Appends OBJECT_<target> to the filenames of LIGHT frames that have no target
name. The target is the nearest, by mount RA/DEC, of the targets in a reference
directory (the primary imaging train of a dual rig), each placed at the median
position of its frames. ap-preserve-header then
writes OBJECT from the filename and ap-move-raw-light-to-blink can organize.
"""

import argparse
import logging
import logging.handlers
import math
import os
import statistics
import sys
from pathlib import Path

import ap_common
from ap_common.constants import (
    NORMALIZED_HEADER_FILENAME,
    NORMALIZED_HEADER_PANEL,
    NORMALIZED_HEADER_TARGETNAME,
    NORMALIZED_HEADER_TYPE,
    TYPE_LIGHT,
)
from ap_common.logging_config import DATE_FORMAT, LOG_FORMAT, setup_logging

from . import config

logger = logging.getLogger(__name__)

EXIT_SUCCESS = 0
EXIT_ERROR = 1

RESULT_RENAMED = "renamed"
RESULT_UNMATCHED = "unmatched"
RESULT_SKIPPED = "skipped"


def angular_separation_degrees(
    ra1: float, dec1: float, ra2: float, dec2: float
) -> float:
    """Great-circle separation (haversine) between two RA/DEC points, degrees."""
    ra1, dec1, ra2, dec2 = map(math.radians, (ra1, dec1, ra2, dec2))
    haversine = (
        math.sin((dec2 - dec1) / 2) ** 2
        + math.cos(dec1) * math.cos(dec2) * math.sin((ra2 - ra1) / 2) ** 2
    )
    return math.degrees(2 * math.asin(min(1.0, math.sqrt(haversine))))


def parse_coordinates(datum: dict) -> tuple[float, float] | None:
    """Return (ra, dec) in degrees, or None if either is missing or invalid."""
    # .get(): ap-common enrichment replaces the datum, dropping absent headers
    try:
        ra = float(datum.get(config.NORMALIZED_HEADER_RA, ""))
        dec = float(datum.get(config.NORMALIZED_HEADER_DEC, ""))
    except (TypeError, ValueError):
        return None
    # NaN/inf or out-of-range would poison a target's median or every match
    if not (math.isfinite(ra) and math.isfinite(dec)):
        return None
    if not (0 <= ra <= 360 and -90 <= dec <= 90):
        return None
    return ra, dec


def load_frames(directory: str, required_properties: list, *, quiet: bool) -> dict:
    """Load metadata for all LIGHT frames under directory (recursive)."""
    return ap_common.get_filtered_metadata(
        dirs=[directory],
        filters={NORMALIZED_HEADER_TYPE: TYPE_LIGHT},
        profileFromPath=False,
        patterns=list(config.INPUT_PATTERNS),
        recursive=True,
        # copy: get_filtered_metadata mutates this list
        required_properties=list(required_properties),
        printStatus=not quiet,
    )


def target_center(coordinates: list[tuple[float, float]]) -> tuple[float, float]:
    """
    Median position of (ra, dec) points, in degrees. Median of each unit-vector
    component: robust to outlier frames, no RA wrap at 0/360, safe at the poles.
    """
    vectors = [
        (
            math.cos(math.radians(dec)) * math.cos(math.radians(ra)),
            math.cos(math.radians(dec)) * math.sin(math.radians(ra)),
            math.sin(math.radians(dec)),
        )
        for ra, dec in coordinates
    ]
    x, y, z = (statistics.median(component) for component in zip(*vectors))
    return (
        math.degrees(math.atan2(y, x)) % 360,
        math.degrees(math.atan2(z, math.hypot(x, y))),
    )


def build_reference(
    reference_data: dict, *, max_frames_per_target: int | None = None
) -> dict[str, tuple[float, float]]:
    """
    Return {target: (ra, dec)} with the median position of each target, using at
    most max_frames_per_target frames per target+panel (None = all).
    """
    coordinates_by_target: dict[str, list[tuple[float, float]]] = {}
    for datum in reference_data.values():
        target = datum.get(NORMALIZED_HEADER_TARGETNAME)
        panel = datum.get(NORMALIZED_HEADER_PANEL)
        if target and panel:
            # undo ap-common's panel split so normalization splits it again later
            target = f"{target} Panel {panel}"
        # target already full: skip before parsing. Can't break, a later frame
        # may be a target not seen yet
        if (
            target
            and max_frames_per_target is not None
            and len(coordinates_by_target.get(target, [])) >= max_frames_per_target
        ):
            continue
        coordinates = parse_coordinates(datum)
        if not target or coordinates is None:
            logger.debug(
                f"Reference frame missing target or RA/DEC, ignoring: "
                f"{datum.get(NORMALIZED_HEADER_FILENAME)}"
            )
            continue
        coordinates_by_target.setdefault(target, []).append(coordinates)

    reference: dict[str, tuple[float, float]] = {}
    for target, frame_coordinates in coordinates_by_target.items():
        invalid = sorted(set(target) & set(config.INVALID_TARGET_CHARACTERS))
        if invalid:
            logger.warning(
                f"Target '{target}' contains {invalid}, not usable in a filename; "
                f"excluded from reference"
            )
            continue
        reference[target] = target_center(frame_coordinates)
    return reference


def find_nearest_target(
    ra: float, dec: float, reference: dict[str, tuple[float, float]]
) -> tuple[str | None, float]:
    """Return (target, separation_degrees) of the nearest reference target."""
    nearest_target = None
    nearest_separation = math.inf
    for target, (reference_ra, reference_dec) in reference.items():
        separation = angular_separation_degrees(ra, dec, reference_ra, reference_dec)
        if separation < nearest_separation:
            nearest_target = target
            nearest_separation = separation
    return nearest_target, nearest_separation


def build_target_filename(filename: str, target: str) -> str:
    """Append _OBJECT_<target> to the filename stem."""
    stem, extension = os.path.splitext(filename)
    return f"{stem}{config.OBJECT_FILENAME_MARKER}{target}{extension}"


def assign_frame(
    datum: dict,
    reference: dict[str, tuple[float, float]],
    *,
    max_separation_degrees: float,
    dryrun: bool,
) -> str:
    """Rename one frame to carry its target. Returns a RESULT_* value."""
    filename = datum[NORMALIZED_HEADER_FILENAME]

    if config.OBJECT_FILENAME_MARKER in os.path.basename(filename):
        logger.debug(f"Already has target in filename, skipping: {filename}")
        return RESULT_SKIPPED

    existing_target = datum.get(NORMALIZED_HEADER_TARGETNAME)
    if existing_target:
        logger.warning(f"Already has target '{existing_target}', skipping: {filename}")
        return RESULT_SKIPPED

    coordinates = parse_coordinates(datum)
    if coordinates is None:
        logger.warning(f"Missing or invalid RA/DEC, skipping: {filename}")
        return RESULT_SKIPPED

    target, separation = find_nearest_target(coordinates[0], coordinates[1], reference)
    logger.debug(
        f"Nearest target: file={filename}, ra={coordinates[0]}, "
        f"dec={coordinates[1]}, target={target}, separation={separation:.4f}"
    )
    if target is None or separation > max_separation_degrees:
        return RESULT_UNMATCHED

    filename_dest = build_target_filename(filename, target)
    if os.path.exists(filename_dest):
        logger.warning(f"Destination exists, skipping: {filename_dest}")
        return RESULT_SKIPPED

    if dryrun:
        print(
            f"Would rename: {filename} -> {os.path.basename(filename_dest)} "
            f"(separation {separation:.4f} deg)"
        )
        return RESULT_RENAMED

    # ponytail: exists-then-rename is not atomic and os.rename replaces on POSIX;
    # fine for one operator on a quiet raw dir (Windows rename refuses to clobber)
    try:
        os.rename(filename, filename_dest)
    except OSError as e:
        # one locked or unreadable file must not abort the rest of the run
        logger.warning(f"Rename failed, skipping: {filename}: {e}")
        return RESULT_SKIPPED
    logger.debug(f"Renamed: {filename} -> {filename_dest}")
    return RESULT_RENAMED


def discover_targetnames(
    source_dir: str,
    reference_dir: str,
    *,
    max_separation_degrees: float,
    max_reference_lights: int | None = None,
    dryrun: bool = False,
    quiet: bool = False,
) -> dict[str, int]:
    """
    Rename LIGHT frames in source_dir to carry the nearest reference target.
    Returns counts keyed by RESULT_* value.
    """
    reference_data = load_frames(
        reference_dir,
        [
            NORMALIZED_HEADER_TARGETNAME,
            config.NORMALIZED_HEADER_RA,
            config.NORMALIZED_HEADER_DEC,
        ],
        quiet=quiet,
    )
    reference = build_reference(
        reference_data, max_frames_per_target=max_reference_lights
    )
    if not reference:
        raise ValueError(
            f"No reference LIGHT frames with target name and RA/DEC: {reference_dir}"
        )
    logger.info(f"Loaded reference targets: {reference}")

    source_data = load_frames(
        source_dir,
        [config.NORMALIZED_HEADER_RA, config.NORMALIZED_HEADER_DEC],
        quiet=quiet,
    )

    counts = {RESULT_RENAMED: 0, RESULT_UNMATCHED: 0, RESULT_SKIPPED: 0}
    for datum in ap_common.progress_iter(
        source_data.values(), desc="Assigning targets", unit="files", enabled=not quiet
    ):
        result = assign_frame(
            datum,
            reference,
            max_separation_degrees=max_separation_degrees,
            dryrun=dryrun,
        )
        counts[result] += 1
    return counts


def _configure_logging(*, debug: bool, quiet: bool, log_file: str | None) -> None:
    """Set up the tool logger; --log-file swaps stderr for a rotating file."""
    tool_logger = setup_logging(name="ap_discover_targetname", debug=debug, quiet=quiet)
    if log_file:
        Path(log_file).parent.mkdir(parents=True, exist_ok=True)
        handler = logging.handlers.RotatingFileHandler(
            log_file, maxBytes=2 * 1024 * 1024, backupCount=1, encoding="utf-8"
        )
        handler.setFormatter(logging.Formatter(LOG_FORMAT, datefmt=DATE_FORMAT))
        tool_logger.handlers.clear()
        tool_logger.addHandler(handler)


def main() -> None:
    """Main entry point for the command-line interface."""
    parser = argparse.ArgumentParser(
        description="Append OBJECT_<target> to filenames of LIGHT frames using "
        "the nearest reference target by RA/DEC"
    )
    parser.add_argument(
        "source_dir", type=str, help="directory of frames missing a target"
    )
    parser.add_argument(
        "reference_dir", type=str, help="directory of frames defining the targets"
    )
    parser.add_argument(
        "--max-separation",
        type=float,
        default=config.DEFAULT_MAX_SEPARATION_DEGREES,
        help="max degrees to nearest reference target",
    )
    parser.add_argument(
        "--max-reference-lights",
        type=int,
        default=None,
        help="max reference frames used per target (default: all)",
    )
    parser.add_argument("--debug", action="store_true", help="enable debug output")
    parser.add_argument(
        "--dryrun", action="store_true", help="perform dry run without renaming"
    )
    parser.add_argument(
        "--quiet", "-q", action="store_true", help="suppress non-essential output"
    )
    parser.add_argument(
        "--log-file", type=str, default=None, help="write log output to file"
    )

    args = parser.parse_args()
    if args.log_file:
        args.log_file = str(Path(args.log_file).expanduser().resolve())

    _configure_logging(debug=args.debug, quiet=args.quiet, log_file=args.log_file)

    try:
        counts = discover_targetnames(
            args.source_dir,
            args.reference_dir,
            max_separation_degrees=args.max_separation,
            max_reference_lights=args.max_reference_lights,
            dryrun=args.dryrun,
            quiet=args.quiet,
        )
    except ValueError as e:
        # expected input problem (e.g. no usable reference frames): message only
        logger.error(f"Error: {e}")
        sys.exit(EXIT_ERROR)
    except Exception:
        logger.exception("Unexpected error")
        sys.exit(EXIT_ERROR)

    if not args.quiet:
        verb = "Would rename" if args.dryrun else "Renamed"
        print(
            f"{verb} {counts[RESULT_RENAMED]} file(s), "
            f"unmatched {counts[RESULT_UNMATCHED]}, "
            f"skipped {counts[RESULT_SKIPPED]}"
        )
    sys.exit(EXIT_SUCCESS)


if __name__ == "__main__":
    main()
